import 'package:news_app_nti/features/home/data/model/source_model.dart';

class ArticlesModel {
  SourceModel? source;
  String? author;
  String? title;
  String? description;
  String? url;
  String? urlToImage;
  String? publishedAt;
  String? content;
  ArticlesModel({
    this.source,
    this.author,
    this.title,
    this.description,
    this.url,
    this.urlToImage,
    this.publishedAt,
    this.content,
  });
  ArticlesModel.fromjson(Map<String, dynamic> json) {
    if (json['source'] != null) {
      source = SourceModel.fromjson(json['source']);
    }
    author = json['author'];
    title = json['title'];
    description = json['description'];
    url = json['url'];
    urlToImage = json['urlToImage'];
    publishedAt = json['publishedAt'];
    content = json['content'];
  }
}
